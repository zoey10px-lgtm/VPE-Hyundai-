package com.vpe.hyundai

import android.app.Activity
import android.app.Instrumentation
import android.content.Intent
import android.graphics.Bitmap
import android.os.Bundle
import android.os.SystemClock
import android.view.MotionEvent
import android.view.View
import android.view.ViewGroup
import android.view.accessibility.AccessibilityNodeInfo
import android.widget.TextView
import org.json.JSONObject
import android.widget.ProgressBar
import android.widget.ScrollView
import java.io.File

/** Runs on a real Android emulator without a third-party test framework. */
class UiRegressionInstrumentation : Instrumentation() {
    override fun onCreate(arguments: Bundle?) { super.onCreate(arguments); start() }

    override fun onStart() {
        val result = Bundle()
        var activity: Activity? = null
        try {
            activity = startActivitySync(Intent().setClassName(targetContext, "com.vpe.hyundai.MainActivity")
                .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
            val screen = activity
            fun call(name: String, vararg args: String) = runOnMainSync {
                val method = screen.javaClass.getDeclaredMethod(name, *Array(args.size) { String::class.java })
                method.isAccessible = true
                method.invoke(screen, *args)
            }
            fun scroll(): ScrollView {
                val field = screen.javaClass.getDeclaredField("pageScroll").apply { isAccessible = true }
                return field.get(screen) as ScrollView
            }
            fun settle() { waitForIdleSync(); SystemClock.sleep(900); waitForIdleSync() }
            fun screenshot(name: String) {
                val file = File(targetContext.getExternalFilesDir(null), name)
                val bitmap = uiAutomation.takeScreenshot() ?: error("No screenshot")
                file.outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
                bitmap.recycle()
            }
            call("loadDemo")
            settle()
            screenshot("ui-report-top.png")
            fun countGauges(view: View): Int = (if (view is ProgressBar) 1 else 0) +
                (if (view is ViewGroup) (0 until view.childCount).sumOf { countGauges(view.getChildAt(it)) } else 0)
            check(countGauges(scroll()) >= 11) { "Report gauges missing" }
            runOnMainSync { scroll().scrollTo(0, 600) }
            settle()
            val before = scroll().scrollY
            check(before > 0) { "Report did not scroll" }
            repeat(3) {
                call("render", "report")
                settle()
                check(scroll().scrollY == before) { "Live refresh reset report scroll: $before -> ${scroll().scrollY}" }
            }
            screenshot("ui-report-gauges.png")
            // A refresh received during a drag must not detach the touched view tree.
            val heldScroll = scroll()
            val point = IntArray(2)
            runOnMainSync { heldScroll.getLocationOnScreen(point) }
            val downTime = SystemClock.uptimeMillis()
            val x = point[0] + 4f
            val y = (point[1] + heldScroll.height / 2).toFloat()
            sendPointerSync(MotionEvent.obtain(downTime, downTime, MotionEvent.ACTION_DOWN, x, y, 0))
            call("render", "report")
            check(scroll() === heldScroll) { "Refresh interrupted active touch" }
            sendPointerSync(MotionEvent.obtain(downTime, SystemClock.uptimeMillis(), MotionEvent.ACTION_UP, x, y, 0))
            settle()
            check(scroll().scrollY == before) { "Deferred refresh lost scroll" }
            call("render", "home")
            settle()
            runOnMainSync { scroll().scrollTo(0, 500) }
            settle()
            val homePosition = scroll().scrollY
            call("render", "home")
            settle()
            check(scroll().scrollY == homePosition) { "Home refresh reset scroll" }
            screenshot("ui-home-cards.png")
            call("render", "report")
            settle()
            check(scroll().scrollY == before) { "Tab navigation lost report position" }
            // Fixture is generated by the production scoring/report modules and is test-only.
            runOnMainSync {
                val fixture = JSONObject(context.assets.open("trait-evidence.json").bufferedReader().use { it.readText() })
                val scope = screen.javaClass.getDeclaredField("activeChatScope").apply { isAccessible = true }.get(screen)
                screen.javaClass.getDeclaredField("serverCharacter").apply { isAccessible = true }.set(screen, fixture)
                screen.javaClass.getDeclaredField("serverCharacterScope").apply { isAccessible = true }.set(screen, scope)
            }
            call("applyServerCharacter")
            call("render", "report")
            settle()
            fun findLabel(view: View, text: String): TextView? {
                if (view is TextView && view.text.toString() == text) return view
                if (view is ViewGroup) for (i in 0 until view.childCount) {
                    findLabel(view.getChildAt(i), text)?.let { return it }
                }
                return null
            }
            runOnMainSync {
                val label = findLabel(scroll(), "호기심") ?: error("Curiosity card missing")
                check((label.parent.parent as View).performClick()) { "Curiosity card not clickable" }
            }
            settle()
            fun nodes(text: String) = uiAutomation.rootInActiveWindow.findAccessibilityNodeInfosByText(text)
            check(nodes("에너지 잔량").isNotEmpty()) { "Received contribution missing" }
            check(nodes("잔량 80%").isNotEmpty()) { "Raw energy evidence missing" }
            check(nodes("%p").isNotEmpty()) { "Contribution amounts missing" }
            check(nodes("미디어 음량").isEmpty()) { "Missing sensor presented as received" }
            screenshot("ui-trait-evidence.png")
            check(nodes("확인").first().performAction(AccessibilityNodeInfo.ACTION_CLICK))
            settle()
            call("showVehicleNameDialog")
            settle()
            screenshot("ui-name-editor.png")
            fun editable(node: AccessibilityNodeInfo): AccessibilityNodeInfo? {
                if (node.isEditable) return node
                for (i in 0 until node.childCount) node.getChild(i)?.let { editable(it)?.let { found -> return found } }
                return null
            }
            val input = editable(uiAutomation.rootInActiveWindow) ?: error("Name input missing")
            check(input.performAction(AccessibilityNodeInfo.ACTION_SET_TEXT, Bundle().apply {
                putCharSequence(AccessibilityNodeInfo.ACTION_ARGUMENT_SET_TEXT_CHARSEQUENCE, "하늘")
            }))
            check(nodes("이름 저장").first().performAction(AccessibilityNodeInfo.ACTION_CLICK))
            settle()
            check(findLabel(scroll(), "01   하늘의 성격 유형") != null) { "Name missing in section title" }
            val pending = screen.javaClass.getDeclaredMethod("pendingReplyText").apply { isAccessible = true }
            check(pending.invoke(screen) == "하늘이 답변을 생각하고 있어요…") { "Named pending copy incorrect" }
            runOnMainSync { scroll().scrollTo(0, 0) }
            settle()
            screenshot("ui-named-report.png")
            call("showVehicleNameDialog")
            settle()
            val emptyInput = editable(uiAutomation.rootInActiveWindow) ?: error("Name input missing")
            emptyInput.performAction(AccessibilityNodeInfo.ACTION_SET_TEXT, Bundle().apply {
                putCharSequence(AccessibilityNodeInfo.ACTION_ARGUMENT_SET_TEXT_CHARSEQUENCE, "")
            })
            nodes("이름 저장").first().performAction(AccessibilityNodeInfo.ACTION_CLICK)
            settle()
            check(pending.invoke(screen) == "내 차가 답변을 생각하고 있어요…") { "Default car name incorrect" }
            check(findLabel(scroll(), "01   내 차의 성격 유형") != null) { "Default report title incorrect" }
            result.putString("stream", "UI_REGRESSION_PASS: report/home refresh, drag deferral, tab positions, gauges, contribution popup, naming, pending copy\n")
            finish(Activity.RESULT_OK, result)
        } catch (error: Throwable) {
            result.putString("stream", "UI_REGRESSION_FAIL: ${error.stackTraceToString()}\n")
            finish(Activity.RESULT_CANCELED, result)
        }
    }
}
